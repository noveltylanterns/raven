/**
 * Escapes text for HTML output.
 */
function installer_e(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES, 'UTF-8');
}

/**
 * Persists runtime config to private/dat/config.php with the standard header block.
 *
 * @param array<string, mixed> $config
 */
function installer_write_config(string $path, array $config): void
{
    $export = var_export($config, true);

    $content = "<?php\n\n";
    $content .= "/**\n";
    $content .= " * RAVEN CMS\n";
    $content .= " * ~/private/dat/config.php\n";
    $content .= " * Runtime configuration values for Raven CMS.\n";
    $content .= " * Docs: https://raven.lanterns.io\n";
    $content .= " */\n\n";
    $content .= "// Inline note: Keep site/database defaults explicit so panel config editing stays predictable.\n\n";
    $content .= "declare(strict_types=1);\n\n";
    $content .= "/**\n";
    $content .= " * Raven runtime configuration (generated by installer).\n";
    $content .= " */\n";
    $content .= "return " . $export . ";\n";

    $written = file_put_contents($path, $content, LOCK_EX);
    if ($written === false) {
        throw new RuntimeException('Failed to write private/dat/config.php');
    }
}

/**
 * Returns the mounted base path that contains this installer script.
 */
function installer_base_path(): string
{
    $scriptName = str_replace('\\', '/', (string) ($_SERVER['SCRIPT_NAME'] ?? '/install.php'));
    if ($scriptName === '' || $scriptName[0] !== '/') {
        $scriptName = '/' . ltrim($scriptName, '/');
    }

    $basePath = dirname($scriptName);
    if ($basePath === '.' || $basePath === '/' || $basePath === '\\') {
        return '';
    }

    return rtrim($basePath, '/');
}

/**
 * Returns the install.php path relative to the current mounted base path.
 */
function installer_path(): string
{
    $basePath = installer_base_path();
    return ($basePath !== '' ? $basePath : '') . '/install.php';
}

/**
 * Returns the public root path for the current mounted base path.
 */
function installer_root_path(): string
{
    $basePath = installer_base_path();
    return $basePath !== '' ? ($basePath . '/') : '/';
}

/**
 * Returns one install-session cookie path scoped to this mounted app root.
 */
function installer_session_cookie_path(): string
{
    return installer_root_path();
}

/**
 * Returns one deterministic installer session name scoped to this mounted app.
 */
function installer_session_name(): string
{
    $seed = installer_path();
    if ($seed === '') {
        $seed = '/install.php';
    }

    return 'raven_install_' . substr(sha1($seed), 0, 12);
}

/**
 * Returns true when one directory is writable or can be created by its parent.
 *
 * @return array{ok: bool, detail: string}
 */
function installer_directory_writable_status(string $path): array
{
    if (is_dir($path)) {
        return [
            'ok' => is_writable($path),
            'detail' => is_writable($path)
                ? 'Writable.'
                : 'Directory exists but is not writable by PHP.',
        ];
    }

    $parent = dirname($path);
    if (!is_dir($parent)) {
        return [
            'ok' => false,
            'detail' => 'Parent directory does not exist.',
        ];
    }

    return [
        'ok' => is_writable($parent),
        'detail' => is_writable($parent)
            ? 'Directory does not exist yet, but PHP can create it.'
            : 'Directory does not exist and parent directory is not writable.',
    ];
}

/**
 * Returns true when Composer dependencies appear fully installed.
 *
 * @return array{ok: bool, detail: string}
 */
function installer_composer_install_status(string $root): array
{
    $requiredPaths = [
        $root . '/composer/autoload.php',
        $root . '/composer/composer/installed.php',
        $root . '/composer/delight-im/auth/src/Auth.php',
    ];

    $missing = [];
    foreach ($requiredPaths as $path) {
        if (!is_file($path)) {
            $missing[] = str_replace($root . '/', '', $path);
        }
    }

    if ($missing !== []) {
        return [
            'ok' => false,
            'detail' => 'Missing ' . implode(', ', $missing) . '. Run `composer install`.',
        ];
    }

    return [
        'ok' => true,
        'detail' => 'Composer autoload and installed packages are present.',
    ];
}

/**
 * Returns database driver support flags for installer choices.
 *
 * @return array{sqlite: bool, mysql: bool, pgsql: bool}
 */
function installer_database_driver_support(): array
{
    $pdoLoaded = extension_loaded('pdo');
    $pdoDrivers = $pdoLoaded && class_exists(PDO::class) ? PDO::getAvailableDrivers() : [];

    return [
        'sqlite' => $pdoLoaded && in_array('sqlite', $pdoDrivers, true) && extension_loaded('pdo_sqlite'),
        'mysql' => $pdoLoaded && in_array('mysql', $pdoDrivers, true) && extension_loaded('pdo_mysql'),
        'pgsql' => $pdoLoaded && in_array('pgsql', $pdoDrivers, true) && extension_loaded('pdo_pgsql'),
    ];
}

function installer_default_database_driver(array $driverSupport, string $fallback = 'sqlite'): string
{
    foreach (['sqlite', 'mysql', 'pgsql'] as $driverKey) {
        if (!empty($driverSupport[$driverKey])) {
            return $driverKey;
        }
    }

    return in_array($fallback, ['sqlite', 'mysql', 'pgsql'], true) ? $fallback : 'sqlite';
}

/**
 * Builds installer pre-flight checklist rows.
 *
 * @return array{
 *   rows: array<int, array{
 *     key: string,
 *     label: string,
 *     status: string,
 *     detail: string,
 *     error: string
 *   }>,
 *   has_fail: bool,
 *   fail_count: int,
 *   warn_count: int,
