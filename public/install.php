spl_autoload_register(static function (string $class) use ($root): void {
    $prefix = 'Raven\\';
    if (!str_starts_with($class, $prefix)) {
        return;
    }

    $relative = str_replace('\\', '/', substr($class, strlen($prefix)));
    $path = $root . '/private/sys/' . $relative . '.php';
    if (is_file($path)) {
        require_once $path;
    }
});

